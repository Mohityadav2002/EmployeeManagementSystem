CREATE OR ALTER VIEW dbo.vw_ActiveEmployees
AS

SELECT

    ---------------------------------------------------------
    -- Employee Information
    ---------------------------------------------------------

    EmployeeId,
    FirstName,
    LastName,
    FullName,

    ---------------------------------------------------------
    -- Gender
    ---------------------------------------------------------

    GenderCode,
    GenderName,

    ---------------------------------------------------------
    -- Department
    ---------------------------------------------------------

    DepartmentCode,
    DepartmentName,

    ---------------------------------------------------------
    -- Role
    ---------------------------------------------------------

    RoleCode,
    RoleName,

    ---------------------------------------------------------
    -- Manager
    ---------------------------------------------------------

    ManagerId,
    ManagerName,

    ---------------------------------------------------------
    -- Contact
    ---------------------------------------------------------

    Email,
    PhoneNumber,

    ---------------------------------------------------------
    -- Address
    ---------------------------------------------------------

    AddressLine1,
    AddressLine2,
    City,
    State,
    Country,
    PinCode,

    ---------------------------------------------------------
    -- Employment
    ---------------------------------------------------------

    DateOfBirth,
    HireDate,
    Salary,
    TotalExperience,

    ---------------------------------------------------------
    -- Status
    ---------------------------------------------------------

    IsActive,
    CreatedDate

FROM dbo.vw_EmployeeDetails

WHERE IsActive = 1;
GO